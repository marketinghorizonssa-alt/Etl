function esc(s='') { return String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c])); }

function section(data) {
  const topics = data.topics.map(([h,p]) => `<article class="campaign-topic"><h3>${esc(h)}</h3><p>${esc(p)}</p></article>`).join('');
  const faq = data.faq.map(([q,a]) => `<details class="campaign-faq"><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('');
  return `<section class="section campaign-keywords" aria-labelledby="campaign-keywords-title"><div class="container"><div class="section-heading"><span>دليل إطلالة للوجهة</span><h2 id="campaign-keywords-title">${esc(data.title)}</h2><p>${esc(data.intro)}</p></div><div class="campaign-topic-grid">${topics}</div><div class="campaign-faq-wrap"><h3>أسئلة شائعة قبل الحجز</h3>${faq}</div></div></section>`;
}

function addFaqSchema(html, data) {
  const schema = { '@context':'https://schema.org', '@type':'FAQPage', mainEntity:data.faq.map(([q,a])=>({ '@type':'Question', name:q, acceptedAnswer:{ '@type':'Answer', text:a } })) };
  if (!html.includes('"@type":"FAQPage"')) html = html.replace('</head>', `<script type="application/ld+json">${JSON.stringify(schema)}</script></head>`);
  return html;
}

