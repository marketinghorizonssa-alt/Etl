for (const [slug,data] of Object.entries(pages)) {
  const file = path.join(out, slug, 'index.html');
  if (!fs.existsSync(file)) continue;
  let html = fs.readFileSync(file,'utf8');
  if (!html.includes('campaign-keywords')) html = html.replace('</main>', `${section(data)}</main>`);
  html = html.replace(/<meta name="description" content="[^"]*">/i, `<meta name="description" content="${esc(data.meta)}">`);
  html = addFaqSchema(html,data);
  fs.writeFileSync(file,html);
  changed++;
}

