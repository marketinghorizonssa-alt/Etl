const esc = (s = '') => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

function dpCards(d) {
  return d.cards.map(([tag, name, text], i) => {
    const image = i === 0 ? `<img class="dp-place-image" src="${d.image}" alt="${esc(d.imageAlt)}" loading="lazy" decoding="async">` : '';
    return `<article class="dp-place dp-place-${i + 1}">${image}<span>${esc(tag)}</span><h3>${esc(name)}</h3><p>${esc(text)}</p></article>`;
  }).join('');
}

function dpMergedSection(d) {
  return `<section class="dp-section dp-soft" id="places"><div class="container"><div class="dp-heading"><span class="dp-kicker">${esc(d.kicker)}</span><h2>${esc(d.heading)}</h2><p>${esc(d.intro)}</p></div><div class="dp-places-grid">${dpCards(d)}</div></div></section>`;
}

for (const [slug, d] of Object.entries(dpPages)) {
  const file = path.join(out, slug, 'index.html');
  if (!fs.existsSync(file)) continue;

  let html = fs.readFileSync(file, 'utf8');
  if (!html.includes('class="dp-page')) continue;

  html = html.replace(/<a href="#places">[^<]*<\/a>/, '<a href="#places">المدن والتجارب</a>');
  html = html.replace(/<a href="#experiences">[^<]*<\/a>/g, '');
  html = html.replace(/<section class="dp-section dp-soft" id="places">[\s\S]*?<\/section>/, dpMergedSection(d));
  html = html.replace(/\s*<section class="dp-section dp-experiences" id="experiences">[\s\S]*?<\/section>\s*/g, '\n');

  fs.writeFileSync(file, html);
}

