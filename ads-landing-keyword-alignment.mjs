function makeSection(d) {
  const cards = d.cards.map(([h,p]) => `<article class="ads-intent-card"><h3>${h}</h3><p>${p}</p></article>`).join('');
  const chips = d.chips.map(x => `<span>${x}</span>`).join('');
  return `<section class="ads-intent-section" aria-labelledby="ads-intent-title"><div class="container"><div class="ads-intent-head"><span class="ads-intent-kicker">${d.kicker}</span><h2 id="ads-intent-title">${d.title}</h2><p>${d.lead}</p></div><div class="ads-intent-grid">${cards}</div><div class="ads-intent-searches" aria-label="طلبات البحث الشائعة"><strong>طلبات شائعة:</strong>${chips}</div></div></section>`;
}

function updateMeta(html, meta) {
  const re = /<meta\s+name=["']description["']\s+content=["'][\s\S]*?["']\s*\/?\s*>/i;
  const tag = `<meta name="description" content="${meta}">`;
  return re.test(html) ? html.replace(re, tag) : html.replace('</head>', `${tag}\n</head>`);
}

function insertSection(html, section, slug) {
  if (html.includes('class="ads-intent-section"')) return html;
  if (slug === 'turkiye') {
    const marker = '<section class="tk-section tk-faq" id="faq">';
    if (html.includes(marker)) return html.replace(marker, section + marker);
  } else if (slug === '') {
    const marker = '<section class="compact-brand">';
    if (html.includes(marker)) return html.replace(marker, section + marker);
  } else {
    const marker = '<section class="dp-section dp-faq" id="faq">';
    if (html.includes(marker)) return html.replace(marker, section + marker);
  }
  return html.replace('</main>', section + '</main>');
}

